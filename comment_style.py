"""评论语域纪律：代码级强制的口语化规则 + 书面套话拦截 + 主动弃评出口。

为什么必须是"代码级"而不是"模板默认值"
--------------------------------------
[auto].comment_prompt / [reply].prompt / [auto].atme_prompt 都是**用户可编辑**
模板，且首次运行即落盘 config.toml，之后**不随插件升级更新**。任何写在配置
默认值里的规则，对已部署实例都等于没写——v1.2.9 加的身份锚点就栽在这里：
代码里的 _DEFAULT_COMMENT_PROMPT 改了，真机 config.toml 仍是旧模板。
因此凡属"发布安全的硬纪律"，一律由本模块在**代码层**拼接，绕开模板。

真机事故（2026-10-03）
--------------------
好友动态「喜报，无料有了，我奶找到了」→ bot 评论
「恭喜！双喜临门，无料和奶奶都到位啦！」被围观嘲笑。拆开是两类问题：

1. **语域错位（真凶）**：「双喜临门」「都到位啦」是官方通稿/书面总结腔。
   朋友说说底下出现这种腔调，一眼就是机器人在汇报——跟前文有没有读懂无关。
2. **硬解梗**：「我奶找到了」是圈内说法，bot 按字面当成一件真事解读，
   还一本正经给出一句"像样"的解释。读不懂时的正确动作是**承认读不懂**
   （或干脆不评论），而不是脑补出一个合理的解释——后者比不回复更伤。

用户定的方向：**读不懂就别装懂、宁可短**。本模块把它拆成三件事：

- `STYLE_GUARD`：追加到每条 prompt 末尾的发言纪律（禁复述总结、口语短句、
  读不懂就直说、禁成语祝语官方腔）；
- `looks_like_stiff_register()`：输出侧 fail-closed 拦书面套话，
  调用方给一次重写机会，仍不合格就放弃发布；
- `SKIP_SENTINELS`：给模型一个**主动弃评出口**（输出 [跳过] 即不评论）。
  "宁可短"的极端形态是"宁可不说"——必须让模型有这个选项，否则它只能硬编。

本模块**纯函数、零依赖**（不 import 插件内其他模块），便于单测覆盖；
发布决策（净化/拒答/身份错位）留在 reply_manager，避免循环依赖。
"""

# ── 发言纪律（代码级，追加到每条评论/回复 prompt 末尾）──────────────────────
# 措辞刻意用"禁令 + 具体反例"：只写"要口语化"模型会当建议，写上具体禁用词
# 才会真的绕开（真机实测「双喜临门」这类词就是被"自然地"选出来的）。
STYLE_GUARD = (
    "\n\n【发言纪律·必须遵守】"
    "1. 不要复述、总结或点评对方说了什么，不要写总结式开头。"
    "2. 像朋友随手回一句，最多20字，一句话能说完就别写第二句，宁可短。"
    "3. 对方的梗、缩写、黑话读不懂就直说读不懂（「没看懂」「啥意思」），"
    "不许猜、不许脑补、不许硬解释成一个像样的意思。"
    "4. 不许用成语、祝福语、书面语和官方腔"
    "（如：双喜临门、都到位、愿你、祝您、请查收）。"
    "5. 实在接不上话，只输出 [跳过] 三个字，不要硬凑。"
)

# 语域不合格时的一次重写提示（把上一句当反例，比抽象要求有效得多）
RETRY_HINT = (
    "\n\n你上一句是「{bad}」——这是书面通稿腔，不是朋友在说话，不能发布。"
    "请重写一句更短更口语的，最多15字；读不懂就说读不懂；"
    "实在接不上话就只输出 [跳过]。"
)

# 模型主动弃评出口：输出以下任一标记即视为"这条我不评论"。
# 之所以要给出口而不是让它硬编：接不上话时模型宁可产出套话也不会交白卷，
# 而套话正是要拦的东西——给它一条体面的退路，它就不硬凑了。
SKIP_SENTINELS = ("[跳过]", "[不评论]", "[略过]")

# ── 书面套话特征（fail-closed）────────────────────────────────────────────
# 命中即判为"通稿腔"。标的是**语域**不是**内容**，所以只收录几乎不可能出现
# 在随手回复里的四字成语/公文体/汇报体；口语里高频的两字词（到位、收到、
# 安排、完美、绝了）一律不收，避免把正常回复误拦。
# 与拒答（_REFUSAL_MARKERS）、身份错位（_IDENTITY_MARKERS）同哲学：
# 误拦只是少一条互动，错发是公开事故。
_STIFF_MARKERS = (
    # 四字成语 / 通稿套话
    "双喜临门",
    "可喜可贺",
    "好事成双",
    "皆大欢喜",
    "锦上添花",
    "万事如意",
    "心想事成",
    "未来可期",
    "前程似锦",
    "乘风破浪",
    "砥砺前行",
    "鹏程万里",
    "步步高升",
    "圆满结束",
    "完美收官",
    "更上一层楼",
    "一举两得",
    "如愿以偿",
    "实至名归",
    "名副其实",
    "叹为观止",
    "感人肺腑",
    "一语中的",
    "大快人心",
    # 祝福 / 公文体
    "祝您",
    "祝愿",
    "愿你",
    "谨祝",
    "顺祝",
    "值此",
    "请查收",
    "敬请期待",
    "感谢您的",
    "您辛苦了",
    "建议您",
    "推荐您",
    "为您",
    # 汇报 / 推销腔
    "都到位",
    "值得拥有",
    "不容错过",
    "强烈推荐",
    # 总结起手式
    "综上所述",
    "总而言之",
    "总结一下",
)


def looks_like_skip(text) -> bool:
    """文本是否为模型主动弃评（输出 [跳过] 之类标记）。

    只看开头若干字符：模型偶尔会在标记后补一句解释（「[跳过]，这个我真看不懂」），
    那也应当算弃评——解释是给我们看的，不是给好友看的。
    """
    if not text:
        return False
    t = str(text).strip()
    if not t:
        return False
    return t.startswith(SKIP_SENTINELS)


def looks_like_stiff_register(text) -> bool:
    """文本是否为书面通稿腔（成语/祝福语/公文体/汇报体）。

    fail-closed：命中即认为不合格。调用方应给一次重写机会，仍不合格再放弃发布。
    误拦代价 = 少一条评论；漏放代价 = 朋友空间里出现一条一眼假的机器人通稿。
    """
    if not text:
        return False
    t = str(text)
    return any(m in t for m in _STIFF_MARKERS)


def append_style_guard(prompt: str) -> str:
    """在 prompt 末尾追加发言纪律（幂等：已含纪律段就不重复追加）。

    幂等很重要——三条生成路径（自动评论 / 回评 / 被@）都要过这里，
    后续若在同一 prompt 上叠加调用，不能出现两段纪律。
    """
    if not prompt:
        return STYLE_GUARD
    p = str(prompt)
    if "【发言纪律" in p:
        return p
    return p + STYLE_GUARD


def build_style_retry_prompt(prompt: str, bad_text: str) -> str:
    """构造语域重写 prompt：把不合格输出作为反例回灌。"""
    base = append_style_guard(prompt)
    return base + RETRY_HINT.format(bad=str(bad_text or "").strip()[:50])
